import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

// Requires ImageMagick with WebP support. Run when adding/replacing a cover:
// node scripts/generate-publication-covers.mjs
const root = fileURLToPath(new URL("../", import.meta.url));
const directory = path.join(root, "client/public/publications");
const output = path.join(directory, "covers");
mkdirSync(output, { recursive: true });
const covers = {};

for (const filename of readdirSync(directory).filter((name) => name.endsWith(".jpg")).sort()) {
  const source = path.join(directory, filename);
  const [width, height] = execFileSync("magick", [
    source, "-auto-orient", "-format", "%w %h", "info:",
  ], { encoding: "utf8" }).trim().split(" ").map(Number);
  const stem = path.parse(filename).name;
  const widths = [...new Set([320, 640, 960, 1280].map((size) => Math.min(size, width)))];
  const variants = widths.map((size) => {
    const name = `${stem}-${size}.webp`;
    execFileSync("magick", [
      source, "-auto-orient", "-resize", `${size}x>`,
      "-strip", "-quality", "80", path.join(output, name),
    ]);
    return { width: size, path: `/publications/covers/${name}` };
  });
  covers[`/publications/${filename}`] = { width, height, variants };
}

writeFileSync(
  path.join(root, "client/src/data/publication-covers.generated.ts"),
  "// Generated by scripts/generate-publication-covers.mjs. Do not edit by hand.\n" +
  `export const publicationCovers = ${JSON.stringify(covers, null, 2)} as const;\n`,
);
